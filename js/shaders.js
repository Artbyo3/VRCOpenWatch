function getActiveShaderSource() {
  if (currentMode === 'flipbook') return generateFlipbookShader();
  if (clockMapping === 'custom') return generateCustomUvClockShader();
  return shaderSource;
}

function refreshShaderPreview() {
  var pre = document.getElementById('shaderCode');
  if (pre) pre.textContent = getActiveShaderSource();
}
/* ===== FLIPBOOK: SHADER GENERATION ===== */
function generateFlipbookShader() {
  var total = flipbookFrames.length;
  var cols = parseInt(gridColsInput.value) || 4;
  var rows = Math.ceil(total / cols) || 1;
  var fps = parseInt(animFpsInput.value) || 12;
  var loop = animLoopInput.checked ? 1 : 0;
  var pingPong = animPingPongInput.checked ? 1 : 0;
  return [
    'Shader "VRChat/VRCOpenWatch/Flipbook"',
    '{',
    '    Properties',
    '    {',
    '        _MainTex ("Sprite Sheet (' + cols + 'x' + rows + ', ' + total + ' frames)", 2D) = "white" {}',
    '        _FrameCount ("Total Frames", Float) = ' + total,
    '        _FPS ("Frames Per Second", Float) = ' + fps,
    '        _Columns ("Grid Columns", Float) = ' + cols,
    '        _Rows ("Grid Rows", Float) = ' + rows,
    '        _Loop ("Loop (1) or Once (0)", Float) = ' + loop,
    '        _PingPong ("Ping-pong (1) or Normal (0)", Float) = ' + pingPong,
    '    }',
    '    SubShader',
    '    {',
    '        Tags { "RenderType"="Opaque" "Queue"="Geometry" }',
    '        Pass',
    '        {',
    '            CGPROGRAM',
    '            #pragma vertex vert',
    '            #pragma fragment frag',
    '            #include "UnityCG.cginc"',
    '',
    '            sampler2D _MainTex;',
    '            float _FrameCount;',
    '            float _FPS;',
    '            float _Columns;',
    '            float _Rows;',
    '            float _Loop;',
    '            float _PingPong;',
    '',
    '            struct appdata { float4 vertex : POSITION; float2 uv : TEXCOORD0; };',
    '            struct v2f { float4 vertex : SV_POSITION; float2 uv : TEXCOORD0; };',
    '',
    '            v2f vert(appdata v)',
    '            {',
    '                v2f o;',
    '                o.vertex = UnityObjectToClipPos(v.vertex);',
    '                o.uv = v.uv;',
    '                return o;',
    '            }',
    '',
    '            fixed4 frag(v2f i) : SV_Target',
    '            {',
    '                float totalFrames = _FrameCount;',
    '                if (totalFrames <= 0.5) return tex2D(_MainTex, i.uv);',
    '',
    '                float frame;',
    '                if (_PingPong > 0.5)',
    '                {',
    '                    float cycle = _Time.y * _FPS;',
    '                    float period = max(1.0, (totalFrames - 1.0) * 2.0);',
    '                    float pos = fmod(cycle, period);',
    '                    frame = pos < totalFrames ? floor(pos) : period - floor(pos);',
    '                }',
    '                else',
    '                {',
    '                    frame = floor(_Time.y * _FPS);',
    '                    if (_Loop < 0.5)',
    '                    {',
    '                        frame = min(frame, totalFrames - 1.0);',
    '                    }',
    '                    frame = fmod(frame, totalFrames);',
    '                }',
    '',
    '                float cols = max(1.0, _Columns);',
    '                float rows = max(1.0, _Rows);',
    '                float col = fmod(frame, cols);',
    '                float row = floor(frame / cols);',
    '',
    '                float u = (col + frac(i.uv.x)) / cols;',
    '                float v = (rows - 1.0 - row + frac(i.uv.y)) / rows;',
    '                float2 atlasUV = float2(u, v);',
    '',
    '                return tex2D(_MainTex, atlasUV);',
    '            }',
    '            ENDCG',
    '        }',
    '    }',
    '}'
  ].join('\n');
}

