function fmtSlotVec(slot) {
  if (!slot) return '(0, 0, 0, 0)';
  return '(' + slot.uMin.toFixed(5) + ', ' + slot.vMin.toFixed(5) + ', ' + slot.uMax.toFixed(5) + ', ' + slot.vMax.toFixed(5) + ')';
}

