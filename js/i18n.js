var currentLang = "en";

function applyLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "jp" ? "ja" : lang;
  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    var key = el.getAttribute("data-i18n");
    if (I18N[lang] && I18N[lang][key] !== undefined) {
      el.textContent = I18N[lang][key];
    }
  });
  if (customFontFamilyName && customFontOption) {
    customFontOption.textContent = I18N[lang].fontPrefix + customFontName;
  }
  document.querySelectorAll(".lang-bar button").forEach(function(btn) {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
  updateClockNote();
  if (typeof updateUvCoords === "function") updateUvCoords();
  if (typeof paintUvPreview === "function") paintUvPreview();
  if (typeof refreshShaderPreview === "function") refreshShaderPreview();
}

document.querySelectorAll(".lang-bar button").forEach(function(btn) {
  btn.addEventListener("click", function() {
    applyLang(this.getAttribute("data-lang"));
  });
});